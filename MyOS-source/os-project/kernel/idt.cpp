namespace idt {

void init() {
    idt_ptr.limit = sizeof(IdtEntry) * IDT_ENTRIES - 1;
    idt_ptr.base  = (uint32_t)&idt_entries;

    for (int i = 0; i < IDT_ENTRIES; i++) set_gate(i, 0, 0, 0);

    remap_pic();

    void (*stub_table[48])() = {
        isr0, isr1, isr2, isr3, isr4, isr5, isr6, isr7, isr8, isr9,
        isr10, isr11, isr12, isr13, isr14, isr15, isr16, isr17, isr18, isr19,
        isr20, isr21, isr22, isr23, isr24, isr25, isr26, isr27, isr28, isr29,
        isr30, isr31, isr32, isr33, isr34, isr35, isr36, isr37, isr38, isr39,
        isr40, isr41, isr42, isr43, isr44, isr45, isr46, isr47
    };

    for (int i = 0; i < 48; i++) {
        set_gate(i, (uint32_t)stub_table[i], 0x08 /* kernel code selector */, 0x8E);
    }

    asm volatile ("lidt (%0)" : : "r"(&idt_ptr));
    kprintf("[idt] loaded %d entries, PIC remapped to vectors 32-47\n", IDT_ENTRIES);
}

void register_handler(uint8_t num, InterruptHandler handler) {
    handlers[num] = handler;
}

} // namespace idt

// Called from isr_common_stub in isr_stubs.s for every exception and IRQ.
extern "C" void isr_common_handler(Registers* regs) {
    if (handlers[regs->int_no]) {
        handlers[regs->int_no](regs);
    } else if (regs->int_no < 32) {
        // Unhandled CPU exception -- this is fatal in our simple kernel.
        kprintf("\n[PANIC] Unhandled CPU exception %d, error code %d\n",
                regs->int_no, regs->err_code);
        for (;;) { asm volatile ("cli; hlt"); }
    }

    // Send End-Of-Interrupt to the PIC(s) for hardware IRQs (32-47).
    if (regs->int_no >= 32 && regs->int_no < 48) {
        if (regs->int_no >= 40) outb(0xA0, 0x20); // slave PIC
        outb(0x20, 0x20);                          // master PIC
    }
}
