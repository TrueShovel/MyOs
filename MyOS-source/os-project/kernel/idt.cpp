#include "idt.h"
#include "io.h"
#include "libc/stdio.h"

namespace {

struct __attribute__((packed)) IdtEntry {
    uint16_t base_low;
    uint16_t selector;
    uint8_t  always0;
    uint8_t  flags;
    uint16_t base_high;
};

struct __attribute__((packed)) IdtPointer {
    uint16_t limit;
    uint32_t base;
};

constexpr int IDT_ENTRIES = 256;
IdtEntry idt_entries[IDT_ENTRIES];
IdtPointer idt_ptr;

InterruptHandler handlers[IDT_ENTRIES] = { nullptr };

void set_gate(uint8_t num, uint32_t base, uint16_t selector, uint8_t flags) {
    idt_entries[num].base_low  = base & 0xFFFF;
    idt_entries[num].base_high = (base >> 16) & 0xFFFF;
    idt_entries[num].selector  = selector;
    idt_entries[num].always0   = 0;
    idt_entries[num].flags     = flags;
}

// Remaps the 8259 Programmable Interrupt Controller so that hardware IRQs
// 0-15 fire interrupt vectors 32-47 instead of their BIOS defaults, which
// overlap with CPU exception vectors 0-15 and would otherwise be
// indistinguishable from them.
void remap_pic() {
    outb(0x20, 0x11); outb(0xA0, 0x11);  // start init sequence
    outb(0x21, 0x20); outb(0xA1, 0x28);  // master offset 32, slave offset 40
    outb(0x21, 0x04); outb(0xA1, 0x02);  // tell each PIC about the other
    outb(0x21, 0x01); outb(0xA1, 0x01);  // 8086 mode
    outb(0x21, 0x00); outb(0xA1, 0x00);  // unmask all IRQs
}

} // namespace

